'use strict';
// Writes public/liturgical.css from lib/liturgical-palette.js.
//   node scripts/build-liturgical-css.js
// test/liturgical.test.js fails when the committed file differs from this output.

const fs = require('fs');
const path = require('path');
const { PALETTE } = require('../lib/liturgical-palette');

const vars = (c) => `  --pc-accent: ${c.accent}; --pc-accent-h: ${c.hover}; --pc-accent-soft: ${c.soft}; --pc-accent-ink: ${c.ink}; --pc-on-accent: ${c.on};
  --lit-1: ${c.g1}; --lit-2: ${c.g2}; --lit-3: ${c.g3};`;

function build() {
  const out = [];
  out.push(`/* GENERATED by scripts/build-liturgical-css.js from lib/liturgical-palette.js: do not edit by hand.

   The liturgical colour a church has applied (lib/liturgical.js) is set on <html data-liturgical="green">.
   It re-colours the app by overriding the accent variables the base theme already uses, plus the four
   places theme-precision.css hard-codes the old purple (the banner, the top bar, the tab underline and
   the logo shadow). It must load after theme-precision.css. */
`);
  for (const [key, p] of Object.entries(PALETTE)) {
    const k = key.toLowerCase();
    out.push(`:root[data-liturgical="${k}"] {\n${vars(p.light)}\n}`);
    out.push(`:root[data-theme="dark"][data-liturgical="${k}"] {\n${vars(p.dark)}\n}`);
  }
  out.push(`
:root[data-liturgical] { --pc-grad: linear-gradient(135deg, var(--lit-1) 0%, var(--lit-2) 55%, var(--lit-3) 100%); }
:root[data-liturgical] .pc-main::before { background: linear-gradient(90deg, var(--lit-1), var(--lit-2) 45%, var(--lit-3)); }
:root[data-liturgical] .pd-head {
  background: radial-gradient(520px 260px at 100% 0%, color-mix(in srgb, var(--lit-3) 60%, transparent), transparent 60%), linear-gradient(135deg, var(--lit-1) 0%, var(--lit-2) 55%, var(--lit-3) 100%);
  box-shadow: 0 18px 40px -22px color-mix(in srgb, var(--lit-1) 70%, transparent);
}
:root[data-theme="dark"][data-liturgical] .pd-head {
  background: radial-gradient(520px 260px at 100% 0%, color-mix(in srgb, var(--lit-3) 45%, transparent), transparent 60%), linear-gradient(135deg, var(--lit-1) 0%, var(--lit-2) 100%);
}
:root[data-liturgical] body.pc .pd .pd-head .pd-actions a.btn:not(.ghost):not(.danger):not(.disabled):not(.quiet):not(.secondary) { color: var(--lit-1) !important; }
:root[data-liturgical] body.pc .pd .pd-head .pd-actions a.btn:not(.ghost):not(.danger):not(.disabled):not(.quiet):not(.secondary):hover { background: var(--pc-accent-soft) !important; }
:root[data-liturgical] .pm-tabs a[aria-current]::after { background: linear-gradient(90deg, var(--lit-1), var(--lit-3)); }
:root[data-liturgical] .pc-ws img { box-shadow: 0 0 0 1px var(--pc-line), 0 4px 10px -4px color-mix(in srgb, var(--lit-2) 50%, transparent); }

/* Almanac page and the colour prompt (colours are data attributes, so no inline style is needed) */
.lit-dot { display: inline-block; flex: none; width: .85em; height: .85em; border-radius: 50%; background: var(--dot, var(--pc-accent)); box-shadow: inset 0 0 0 1px rgba(0, 0, 0, .25); vertical-align: -.08em; }
.lit-chip { display: inline-flex; align-items: center; gap: 6px; padding: 2px 10px 2px 8px; border-radius: 999px; font-size: 13px; font-weight: 600; background: var(--pc-accent-soft); color: var(--pc-accent-ink); }
.lit-prompt { flex-wrap: wrap; align-items: center; gap: 10px 14px; }
.lit-prompt form { display: inline-flex; flex-wrap: wrap; gap: 8px; margin: 0; }
.lit-prompt > span:not(.lit-dot) { flex: 1 1 280px; }
.pd-callout .lit-dot { flex: none; }
.lit-now { display: flex; flex-wrap: wrap; align-items: center; gap: 10px 16px; }
.lit-now form { display: inline-flex; flex-wrap: wrap; align-items: center; gap: 8px; margin: 0; }
.almanac-list { display: grid; gap: 12px; margin: 0; padding: 0; list-style: none; }
.almanac-entry { border: 1px solid var(--pc-line); border-left: 5px solid var(--dot, var(--pc-accent)); border-radius: var(--pc-r); background: var(--pc-panel); padding: 14px 16px; }
.almanac-entry.is-now { box-shadow: 0 0 0 2px var(--dot, var(--pc-accent)); }
.almanac-entry header { display: flex; flex-wrap: wrap; align-items: baseline; gap: 4px 12px; margin-bottom: 8px; }
.almanac-entry h3 { margin: 0; font-size: 16px; }
.almanac-entry .when { color: var(--pc-text-2); font-size: 14px; }
.almanac-entry .theme { margin: 0 0 8px; font-weight: 600; }
.almanac-entry dl { display: grid; grid-template-columns: repeat(auto-fit, minmax(230px, 1fr)); gap: 10px 20px; margin: 0; }
.almanac-entry dt { font-size: 12px; text-transform: uppercase; letter-spacing: .04em; color: var(--pc-text-2); margin-bottom: 2px; }
.almanac-entry dd { margin: 0; }
.lit-badge { display: inline-block; padding: 2px 10px; border-radius: 999px; font-size: 12px; font-weight: 600; border: 1px solid var(--pc-line); color: var(--pc-text-2); }
.almanac-entry .lit-readings { list-style: none; padding-left: 0; }
.almanac-entry .lit-readings li > b { display: inline-block; min-width: 9.5em; font-size: 13px; color: var(--pc-text-2); }
.almanac-entry ol, .almanac-entry ul { margin: 0; padding-left: 18px; }
`);
  for (const [key, p] of Object.entries(PALETTE)) {
    out.push(`[data-c="${key}"] { --dot: ${p.swatch}; }`);
  }
  return out.join('\n') + '\n';
}

if (require.main === module) {
  const file = path.join(__dirname, '..', 'public', 'liturgical.css');
  fs.writeFileSync(file, build());
  console.log(`wrote ${path.relative(process.cwd(), file)}`);
}

module.exports = { build };
